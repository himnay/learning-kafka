-- Library events consumed from the library-events topic.
-- Column names follow Spring Boot's default naming (camelCase -> snake_case).
CREATE TABLE library_event (
    library_event_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_event_type VARCHAR(20) NOT NULL CHECK (library_event_type IN ('NEW', 'UPDATE'))
);

CREATE TABLE book (
    book_id          INTEGER PRIMARY KEY,
    book_name        VARCHAR(255),
    book_author      VARCHAR(255),
    library_event_id INTEGER UNIQUE REFERENCES library_event (library_event_id)
);
